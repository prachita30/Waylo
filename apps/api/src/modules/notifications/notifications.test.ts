type Agent = ReturnType<TestApp['agent']>;
let n = 0;
async function account(phone?: string): Promise<{ a: Agent; id: string; email: string }> {
  const a = t.agent();
  const email = `notify${Date.now()}${n++}@example.com`;
  const r = await a.post('/api/v1/auth/register').send({ fullName: 'Noor Khan', email, password: 'journey2026', acceptTerms: true, phone });
  return { a, id: r.body.user.id, email };
}
const PNG = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNk+M9QDwADhgGAWjR9awAAAABJRU5ErkJggg==', 'base64');

async function confirmedBooking(a: Agent) {
  const date = addDays(localDate(new Date(), 'Asia/Kolkata'), 8);
  const search = await a.get('/api/v1/flights/search').query({ from: 'BOM', to: 'GOI', date, adults: 1, pageSize: 50 });
  const offer = (search.body.items as OfferDto[]).find((o) => o.source === 'airline' && ['available', 'limited'].includes(o.availability))!;
  const v = await a.post(`/api/v1/flights/offers/${offer.id}/validate`).send({ adults: 1 });
  const b = await a
    .post('/api/v1/flights/bookings')
    .set('Idempotency-Key', `notify-${Date.now()}-${n++}`)
    .send({ priceLockId: v.body.lock.id, passengers: [{ firstName: 'Noor', lastName: 'Khan' }], contact: { email: 'noor@example.com' }, acceptedTotalMinor: v.body.lock.totalMinor, acceptFareRules: true });
  await a.post(`/api/v1/payments/sandbox/intents/${b.body.checkoutUrl.split('/').pop()}/complete`).send({ outcome: 'succeed' });
  return b.body.booking as { id: string; reference: string };
}

describe('notifications', () => {
  it('notifies the traveller in-app and by email/push when a ticket is issued', async () => {
    const { a, email } = await account();
    const booking = await confirmedBooking(a);
    const list = (await a.get('/api/v1/notifications')).body;
    const n1 = list.items.find((x: { kind: string }) => x.kind === 'flight_booking.confirmed');
    expect(n1).toMatchObject({ title: 'Your flight is confirmed', link: `/trips/flights/${booking.id}`, readAt: null });
    expect(n1.body).toContain(booking.reference);
    expect(list.unread).toBeGreaterThanOrEqual(1);

    await sendQueuedDeliveries(t.ctx);
    const deliveries = await t.ctx.db.select().from(notificationDeliveries).where(eq(notificationDeliveries.notificationId, n1.id));
    expect(Object.fromEntries(deliveries.map((d) => [d.channel, d.status]))).toEqual({ email: 'sent', sms: 'skipped', push: 'sent' });
    const mail = messaging.outbox.find((m) => m.channel === 'email' && m.message.to === email);
    expect(mail).toBeTruthy();
    if (mail?.channel === 'email') {
      expect(mail.message.subject).toBe('Your flight is confirmed');
      expect(mail.message.html).toContain('WAYLO');
      expect(mail.message.html).toContain('Sandbox message');
      expect(mail.message.html).not.toMatch(/vite|react|generated by|powered by/i);
    }
  });

  it('respects channel preferences and sends SMS only with a mobile number', async () => {
    const { a, id } = await account('+919876500001');
    await a.put('/api/v1/users/me/preferences').send({ notifyEmail: false, notifySms: true, notifyPush: false, marketingOptIn: false });
    await emit(t.ctx, { type: 'support.ticket_updated', userId: id, ticketId: '00000000-0000-0000-0000-000000000000', status: 'in_review' });
    const [row] = await t.ctx.db.select().from(notifications).where(eq(notifications.userId, id));
    const deliveries = await t.ctx.db.select().from(notificationDeliveries).where(eq(notificationDeliveries.notificationId, row!.id));
    expect(deliveries.map((d) => d.channel)).toEqual(['sms']);
    await sendQueuedDeliveries(t.ctx);
    expect(messaging.outbox.some((m) => m.channel === 'sms' && m.message.to === '+919876500001')).toBe(true);
  });

  it('retries failed deliveries with backoff, then gives up', async () => {
    const { id } = await account();
    await emit(t.ctx, { type: 'refund.processed', userId: id, amountMinor: 50_000, reference: 'r', succeeded: true });
    const [row] = await t.ctx.db.select().from(notifications).where(eq(notifications.userId, id));
    const [email] = (await t.ctx.db.select().from(notificationDeliveries).where(eq(notificationDeliveries.notificationId, row!.id))).filter((d) => d.channel === 'email');
    let now = new Date();
    for (let i = 0; i < 3; i++) {
      messaging.failNext = 10;
      await sendQueuedDeliveries(t.ctx, now);
      now = new Date(now.getTime() + 20 * 60_000);
    }
    messaging.failNext = 0;
    const [after] = await t.ctx.db.select().from(notificationDeliveries).where(eq(notificationDeliveries.id, email!.id));
    expect(after).toMatchObject({ status: 'failed', attempts: 3 });
  });

  it('marks notifications read only for their owner', async () => {
    const { a, id } = await account();
    const other = await account();
    await emit(t.ctx, { type: 'refund.processed', userId: id, amountMinor: 10_000, reference: 'x', succeeded: false });
    const mine = (await a.get('/api/v1/notifications')).body.items[0];
    expect(mine.title).toBe('Your refund needs attention');
    await other.a.post('/api/v1/notifications/read').send({ ids: [mine.id] });
    expect((await a.get('/api/v1/notifications')).body.unread).toBe(1);
    await a.post('/api/v1/notifications/read').send({ ids: 'all' });
    expect((await a.get('/api/v1/notifications')).body.unread).toBe(0);
  });
});

describe('support', () => {
  it('creates a ticket with an attachment, links a booking, and keeps the thread private', async () => {
    const { a } = await account();
    const booking = await confirmedBooking(a);
    const res = await a
      .post('/api/v1/support/tickets')
      .field('category', 'booking')
      .field('subject', 'Name spelling on ticket')
      .field('message', 'My last name is misspelled on the ticket, please help.')
      .field('bookingRef', booking.reference)
      .attach('attachment', PNG, { filename: 'id.png', contentType: 'image/png' });
    expect(res.status).toBe(201);
    const ticket = res.body.ticket;
    expect(ticket.reference).toMatch(/^SR[A-Z2-9]{6}$/);
    expect(ticket.relatedBookingRef).toBe(booking.reference);
    expect(ticket.messages[0].attachment.url).toMatch(/\/api\/v1\/support\/attachments\//);
    expect((await a.get(ticket.messages[0].attachment.url)).headers['content-type']).toBe('image/png');

    const stranger = await account();
    expect((await stranger.a.get(`/api/v1/support/tickets/${ticket.id}`)).status).toBe(404);
    expect((await stranger.a.get(ticket.messages[0].attachment.url)).status).toBe(404);
    const wrongBooking = await stranger.a.post('/api/v1/support/tickets').send({ category: 'booking', subject: 'Not mine', message: 'Trying to attach someone else booking.', bookingRef: booking.reference });
    expect(wrongBooking.status).toBe(400);
  });

  it('lets an agent reply, keeps internal notes hidden, and notifies the customer', async () => {
    const { a } = await account();
    const t1 = (await a.post('/api/v1/support/tickets').send({ category: 'payment_refund', subject: 'Refund not received', message: 'It has been ten days since my refund.' })).body.ticket;
    expect(t1.priority).toBe('high');
    const admin = await t.loginAs('admin@demo.waylo.app');
    const queue = (await admin.get('/api/v1/admin/support/tickets')).body.items;
    expect(queue.some((x: { id: string }) => x.id === t1.id)).toBe(true);
    await admin.post(`/api/v1/admin/support/tickets/${t1.id}/messages`).send({ message: 'Checked provider: refund settled on day 3.', internal: true });
    const reply = await admin.post(`/api/v1/admin/support/tickets/${t1.id}/messages`).send({ message: 'Your refund was sent on 3 Oct. Banks can take up to 7 days.' });
    expect(reply.body.ticket.status).toBe('awaiting_customer');

    const seen = (await a.get(`/api/v1/support/tickets/${t1.id}`)).body.ticket;
    expect(seen.messages.map((m: { author: string }) => m.author)).toEqual(['You', 'WAYLO Support']);
    expect(JSON.stringify(seen)).not.toContain('Checked provider');
    const notes = (await a.get('/api/v1/notifications')).body.items;
    expect(notes.some((x: { kind: string; link: string }) => x.kind === 'support.ticket_updated' && x.link === `/support/tickets/${t1.id}`)).toBe(true);

    const back = await a.post(`/api/v1/support/tickets/${t1.id}/messages`).send({ message: 'Thanks, found it.' });
    expect(back.body.ticket.status).toBe('open');
    await a.post(`/api/v1/support/tickets/${t1.id}/close`);
    expect((await a.post(`/api/v1/support/tickets/${t1.id}/messages`).send({ message: 'One more thing' })).status).toBe(409);
    expect((await a.get('/api/v1/admin/support/tickets')).status).toBe(403);
  });

  it('escalates safety reports as urgent and opens a safety incident', async () => {
    const { a, id } = await account();
    const t1 = (await a.post('/api/v1/support/tickets').send({ category: 'safety', subject: 'Unsafe driving', message: 'The driver was using the phone while driving fast.' })).body.ticket;
    expect(t1.priority).toBe('urgent');
    expect(t1.incidentId).toBeTruthy();
    const [incident] = await t.ctx.db.select().from(safetyIncidents).where(eq(safetyIncidents.id, t1.incidentId));
    expect(incident).toMatchObject({ reporterUserId: id, category: 'safety', severity: 'high', status: 'open' });
  });

  it('rejects disguised attachments', async () => {
    const { a } = await account();
    const res = await a.post('/api/v1/support/tickets').field('category', 'other').field('subject', 'Hello there').field('message', 'Please see the attached file.').attach('attachment', Buffer.from('<script>alert(1)</script>'), { filename: 'x.png', contentType: 'image/png' });
    expect(res.status).toBe(400);
  });
});
