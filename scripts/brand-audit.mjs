#!/usr/bin/env node
/**
 * White-label audit. Fails if third-party tool, template or AI-assistant branding appears in what
 * users receive: the built web app (HTML, manifest, images, scripts) and the transactional email
 * source. Also fails if the public build contains source maps.
 *
 * Run after `npm run build`:  node scripts/brand-audit.mjs
 */
import { readdirSync, readFileSync, statSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(root, 'apps/web/dist');

// Terms that would credit a tool or template rather than WAYLO. Library code in bundles naturally
// mentions frameworks internally, so framework names are only checked in user-facing text files.
const ALWAYS = [/lovable/i, /bolt\.new/i, /\bv0\.dev\b/i, /made with/i, /powered by/i, /built with/i, /lorem ipsum/i];
const TEXT_ONLY = [/\bvite\b/i, /\breact\b/i, /tailwind/i, /shadcn/i, /template/i];

const problems = [];
const walk = (dir) =>
  readdirSync(dir).flatMap((name) => {
    const full = path.join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });

let files;
try {
  files = walk(dist);
} catch {
  console.error('apps/web/dist not found. Run `npm run build` first.');
  process.exit(2);
}

for (const file of files) {
  const rel = path.relative(root, file).replace(/\\/g, '/');
  if (file.endsWith('.map')) {
    problems.push(`${rel}: source map in public build`);
    continue;
  }
  if (/\.(png|jpe?g|webp|ico|woff2?)$/.test(file)) continue;
  const text = readFileSync(file, 'utf8');
  const isUserText = /\.(html|webmanifest|svg|txt|json)$/.test(file);
  for (const re of isUserText ? [...ALWAYS, ...TEXT_ONLY] : ALWAYS) {
    const m = text.match(re);
    if (m) problems.push(`${rel}: "${text.slice(Math.max(0, m.index - 40), m.index + m[0].length + 40).replace(/\s+/g, ' ')}"`);
  }
}

// Email HTML is assembled in the API; check the template source for credits.
const email = readFileSync(path.join(root, 'apps/api/src/modules/notifications/email.ts'), 'utf8');
for (const re of [/made with/i, /powered by/i, /generated by/i]) {
  if (re.test(email.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, ''))) problems.push(`apps/api/src/modules/notifications/email.ts: matches ${re}`);
}

if (problems.length) {
  console.error(`Brand audit failed (${problems.length}):\n- ${problems.join('\n- ')}`);
  process.exit(1);
}
console.log(`Brand audit passed: ${files.length} built files checked, no third-party branding or source maps.`);
